#!/usr/bin/env bash
# This disposable fixture does not operate on an existing deployment.
set -euo pipefail

suffix="$(od -An -N16 -tx1 /dev/urandom | tr -d ' \n')"
network="dove-pg-upgrade-test-$suffix"
old="dove-pg17-test-$suffix"
new="dove-pg18-test-$suffix"
old_volume="dove-pg17-test-$suffix"
new_volume="dove-pg18-test-$suffix"
tmpdir="$(mktemp -d)"
network_created=0
old_volume_created=0
new_volume_created=0
old_created=0
new_created=0
cleanup() {
  if ((old_created)); then docker rm -f "$old" >/dev/null 2>&1 || true; fi
  if ((new_created)); then docker rm -f "$new" >/dev/null 2>&1 || true; fi
  if ((old_volume_created)); then docker volume rm "$old_volume" >/dev/null 2>&1 || true; fi
  if ((new_volume_created)); then docker volume rm "$new_volume" >/dev/null 2>&1 || true; fi
  if ((network_created)); then docker network rm "$network" >/dev/null 2>&1 || true; fi
  rm -rf -- "$tmpdir"
}
trap cleanup EXIT

wait_ready() {
  local container="$1" user="$2" password="${3:-fixture-admin-password}"
  for _ in {1..60}; do
    if docker exec "$container" pg_isready -U "$user" -d postgres >/dev/null 2>&1; then
      # pg_isready can succeed during initdb's temporary server. Require TCP.
      if docker exec -e PGPASSWORD="$password" "$container" \
          psql -X -h 127.0.0.1 -U "$user" -d postgres -Atqc 'SELECT 1' >/dev/null 2>&1; then
        return 0
      fi
    fi
    sleep 1
  done
  docker logs "$container"
  return 1
}
assert_eq() {
  local expected="$1" actual="$2" description="$3"
  if [[ "$actual" != "$expected" ]]; then
    printf '%s: expected <%s>, got <%s>\n' "$description" "$expected" "$actual" >&2
    exit 1
  fi
}

# Refuse to use a pre-existing volume or network; only remove resources this
# fixture successfully created. Container creation itself rejects name clashes.
if docker network inspect "$network" >/dev/null 2>&1 || \
   docker volume inspect "$old_volume" >/dev/null 2>&1 || \
   docker volume inspect "$new_volume" >/dev/null 2>&1; then
  echo 'Fixture resource name already exists; refusing to proceed.' >&2
  exit 1
fi
docker network create "$network" >/dev/null
network_created=1
docker volume create "$old_volume" >/dev/null
old_volume_created=1
docker volume create "$new_volume" >/dev/null
new_volume_created=1
docker create --name "$old" --network "$network" --network-alias source \
  -e POSTGRES_USER=dove -e POSTGRES_DB=dove -e POSTGRES_PASSWORD=fixture-admin-password \
  -v "$old_volume:/var/lib/postgresql/data" postgres:17.6-alpine >/dev/null
old_created=1
docker start "$old" >/dev/null
wait_ready "$old" dove

docker exec -i "$old" psql -X -v ON_ERROR_STOP=1 -U dove -d dove <<'SQL'
CREATE ROLE app_reader LOGIN PASSWORD 'fixture-reader-password';
CREATE ROLE reporting NOLOGIN;
GRANT reporting TO app_reader;
CREATE TABLE inventory (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item text NOT NULL);
INSERT INTO inventory (item) VALUES ('alpha'), ('café'), ('third row');
SELECT setval(pg_get_serial_sequence('inventory','id'), 42, true);
REVOKE CONNECT ON DATABASE dove FROM PUBLIC;
REVOKE USAGE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE dove TO app_reader;
GRANT USAGE ON SCHEMA public TO app_reader;
GRANT SELECT ON inventory TO app_reader;
CREATE DATABASE archive;
SQL
docker exec -i "$old" psql -X -v ON_ERROR_STOP=1 -U dove -d archive <<'SQL'
CREATE TABLE retained (value text NOT NULL);
INSERT INTO retained VALUES ('other database');
SQL

docker create --name "$new" --network "$network" --network-alias target \
  -e POSTGRES_USER=dove -e POSTGRES_DB=postgres -e POSTGRES_PASSWORD=fixture-target-bootstrap-password \
  -v "$new_volume:/var/lib/postgresql" postgres:18.4-alpine >/dev/null
new_created=1
docker start "$new" >/dev/null
wait_ready "$new" dove fixture-target-bootstrap-password
# Use the newer client for the entire cluster (including roles). Dump is synthetic,
# private to this runner, and removed on exit. Do not upload it as an artifact.
docker exec -e PGPASSWORD=fixture-admin-password "$new" \
  pg_dumpall -h source -U dove --quote-all-identifiers > "$tmpdir/cluster.sql"
# Both disposable clusters use the same bootstrap superuser so grants recorded
# with that grantor remain valid. It already exists on the target; remove only
# its exact CREATE statement and fail closed if the expected dump shape changes.
# This is specific to the synthetic fixture, not a general dump rewriting tool.
awk '$0 == "CREATE ROLE \"dove\";" { found++; next } { print } END { if (found != 1) exit 1 }' \
  "$tmpdir/cluster.sql" > "$tmpdir/restore.sql"
# This is a quiescent fixture; stop the old server before restoring/cutover.
docker stop "$old" >/dev/null
docker exec -i "$new" psql -X -v ON_ERROR_STOP=1 -U dove -d postgres < "$tmpdir/restore.sql"

assert_eq 18 "$(docker exec "$new" psql -X -U dove -d postgres -Atqc "SELECT current_setting('server_version_num')::int / 10000")" 'target major version'
assert_eq '3|alpha,café,third row' "$(docker exec -e PGPASSWORD=fixture-reader-password "$new" psql -X -h target -U app_reader -d dove -Atqc "SELECT count(*) || '|' || string_agg(item, ',' ORDER BY id) FROM inventory")" 'reader authentication, grants and rows'
assert_eq '42|t' "$(docker exec "$new" psql -X -U dove -d dove -Atqc "SELECT last_value, is_called FROM inventory_id_seq")" 'sequence state'
assert_eq 'other database' "$(docker exec "$new" psql -X -U dove -d archive -Atqc 'SELECT value FROM retained')" 'second database'
assert_eq f "$(docker exec "$new" psql -X -U dove -d postgres -Atqc "SELECT rolsuper FROM pg_roles WHERE rolname='app_reader'")" 'reader remains non-superuser'
assert_eq t "$(docker exec "$new" psql -X -U dove -d postgres -Atqc "SELECT pg_has_role('app_reader', 'reporting', 'MEMBER')")" 'role membership'
assert_eq 'dove|false|true|true' "$(docker exec "$new" psql -X -U dove -d postgres -Atqc "SELECT pg_get_userbyid(grantor) || '|' || admin_option || '|' || inherit_option || '|' || set_option FROM pg_auth_members WHERE roleid='reporting'::regrole AND member='app_reader'::regrole")" 'membership grantor and options'
assert_eq dove "$(docker exec "$new" psql -X -U dove -d dove -Atqc "SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid='public.inventory'::regclass")" 'table ownership'
assert_eq 1 "$(docker exec -e PGPASSWORD=fixture-admin-password "$new" psql -X -h target -U dove -d dove -Atqc 'SELECT 1')" 'restored admin password authentication'
if docker exec -e PGPASSWORD=fixture-target-bootstrap-password "$new" \
    psql -X -h target -U dove -d dove -Atqc 'SELECT 1' >/dev/null 2>&1; then
  echo 'Target bootstrap password unexpectedly remains valid after restore.' >&2
  exit 1
fi
# Rollback is safe only before writes to the new cluster: restart the untouched
# source volume and confirm its data. Later writes need a separate recovery plan.
docker stop "$new" >/dev/null
docker start "$old" >/dev/null
wait_ready "$old" dove
assert_eq 17 "$(docker exec "$old" psql -X -U dove -d postgres -Atqc "SELECT current_setting('server_version_num')::int / 10000")" 'rollback major version'
assert_eq '3|alpha,café,third row' "$(docker exec -e PGPASSWORD=fixture-reader-password "$old" psql -X -h source -U app_reader -d dove -Atqc "SELECT count(*) || '|' || string_agg(item, ',' ORDER BY id) FROM inventory")" 'rollback data and reader authentication'
assert_eq 'other database' "$(docker exec "$old" psql -X -U dove -d archive -Atqc 'SELECT value FROM retained')" 'rollback second database'
echo 'Synthetic PostgreSQL 17 to 18 restore and pre-write rollback passed.'
